'use strict';
const { spawn } = require('node:child_process');
const path = require('node:path');
const output = process.env.COSTATS_SMOKE_OUTPUT || path.resolve(__dirname, '../../artifacts/smoke');
const env = { ...process.env, COSTATS_SMOKE_OUTPUT: output };
delete env.ELECTRON_RUN_AS_NODE;
const packaged = process.argv[2];
const child = spawn(packaged ? path.resolve(packaged) : require('electron'), packaged ? ['--smoke'] : [path.resolve(__dirname, '..'), '--smoke'], { env, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
child.stdout.pipe(process.stdout);
child.stderr.pipe(process.stderr);
const deadline = setTimeout(() => { child.kill(); process.exitCode = 1; console.error('Desktop smoke test timed out.'); }, 60000);
child.on('error', () => { clearTimeout(deadline); process.exitCode = 1; });
child.on('exit', code => { clearTimeout(deadline); process.exitCode = code ?? 1; });
